"""Dataset card generation (composition, processing, limitations, intended use, provenance)."""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING

from dataforge.reporting.tables import fmt_bytes, fmt_int, fmt_pct, md_table

if TYPE_CHECKING:
    from dataforge.reporting.report import ReportContext


def write_data_card(
    path: Path,
    ctx: ReportContext,
    domains: list[tuple[str, int, int, int]],
    languages: list[tuple[str, int, int, int]],
) -> None:
    manifest = ctx.manifest
    config = ctx.loaded.config
    stages = config.stages
    total = manifest.totals.documents
    synthetic = any(s.type == "synthetic" for s in manifest.sources) or any(
        "synthetic" in (src.config.description or "").lower() for src in ctx.loaded.sources
    )
    source_rows = [
        [
            s.source_id,
            s.type,
            f"per record (`{s.license_field}`)" if s.license_field else s.license,
            s.license_source or "-",
            s.usage_policy,
            fmt_int(s.documents_read),
        ]
        for s in manifest.sources
    ]
    stage_rows = []
    for node in ctx.plan.nodes:
        stats = ctx.stage(node.name)
        removed = (stats.documents_in - stats.documents_out) if stats else 0
        stage_rows.append([node.name, node.kind, node.mode, node.description, fmt_int(removed)])
    benchmark_rows = [
        [b.name, b.license, "yes" if b.available else "no", fmt_int(b.items)] for b in manifest.benchmarks
    ]
    lines = [
        f"# Dataset card: {manifest.name}",
        "",
        f"`{manifest.dataset_id}` - generated by DataForge {manifest.code.dataforge_version} on {manifest.created_at}.",
        "",
        config.pipeline.description or "Pretraining dataset produced by a DataForge pipeline.",
        "",
        "## Summary",
        "",
        (
            f"- Documents: {fmt_int(total)} ({fmt_bytes(manifest.totals.text_bytes)} of text, "
            f"{fmt_int(manifest.totals.tokens)} estimated tokens with `{manifest.tokenizer}`)"
        ),
        "- Splits: " + ", ".join(f"{name} {fmt_int(s.documents)}" for name, s in manifest.splits.items()),
        (
            f"- Format: {manifest.shards[0].format if manifest.shards else 'n/a'} shards with the DataForge document "
            f"schema v{manifest.document_schema_version} (`text` plus metadata and provenance columns)"
        ),
        "",
        "## Sources and licenses",
        "",
        md_table(
            ["Source", "Type", "License", "License evidence", "Usage policy", "Documents read"],
            source_rows,
            "lllllr",
        ),
        "",
        f"Licenses come from source metadata and are never inferred; documents with an `UNKNOWN` license are "
        f"handled by policy `{stages.license.unknown_policy}`. Allowed licenses: "
        + ", ".join(f"`{lic}`" for lic in stages.license.allowed)
        + ". This card is not legal advice.",
        "",
        "## Composition",
        "",
        md_table(
            ["Domain", "Documents", "Share"],
            [[d, fmt_int(n), fmt_pct(n, total)] for d, n, _, _ in domains],
            "lrr",
        ),
        "",
        md_table(
            ["Language", "Documents", "Share"],
            [[lang, fmt_int(n), fmt_pct(n, total)] for lang, n, _, _ in languages],
            "lrr",
        ),
        "",
        "## Processing",
        "",
        md_table(["Stage", "Kind", "Mode", "What it does", "Documents removed"], stage_rows, "llllr"),
        "",
        (
            "Full statistics, removal reasons, and plots are in `reports/report.md`; every removal is listed by "
            "document "
            "id in `reports/removals.parquet`."
        ),
        "",
        "## Contamination control",
        "",
        (
            md_table(["Benchmark", "License", "Available", "Items"], benchmark_rows, "llcr")
            if benchmark_rows
            else "No benchmarks were checked."
        ),
        "",
        "## Intended use",
        "",
        "- Pretraining or continued pretraining of language models, and research on data-processing choices.",
        "- Reproducibility studies: the manifest pins sources, configuration, and code.",
        "",
        "## Out-of-scope use",
        "",
        "- Any use the source licenses or usage policies do not permit.",
        "- Treating heuristic quality, language, or domain labels as ground truth.",
        "- Evaluation on the benchmarks listed above without re-checking contamination for your own test sets.",
        "",
        "## Known limitations and biases",
        "",
        (
            "- Quality filtering is heuristic (length, repetition, symbol and URL ratios, boilerplate, "
            "punctuation); it "
            "favours well-formed prose and can remove legitimate lists, poetry, tables, or dialectal text."
        ),
        (
            "- The built-in language detector covers a small set of languages and is weak on short or mixed-language "
            "text; non-target languages may be under-represented by design."
        ),
        "- Domain labels come from keyword and URL rules and inherit their blind spots.",
        (
            "- PII and secret detection is pattern based: it misses unstructured personal data and can flag "
            "look-alikes. Redaction placeholders (`<EMAIL>`, `<SECRET>`) remain in the text."
        ),
        (
            "- Deduplication is document-level by default; near-duplicate detection is probabilistic (MinHash) with a "
            "Jaccard threshold, so lightly edited copies below the threshold remain."
        ),
    ]
    if synthetic:
        lines.append(
            "- **This dataset was built from synthetic sample data** generated by DataForge for demonstration; its "
            "content is template-generated and not suitable for training real models."
        )
    lines += [
        "",
        "## Provenance",
        "",
        f"- Manifest: `manifest.json` (schema {manifest.schema_version}); dataset fingerprint `{manifest.fingerprint}`",
        (
            f"- Pipeline config `{manifest.pipeline.config_path}`, hash `{manifest.pipeline.config_hash}` "
            "(embedded in the manifest)"
        ),
        f"- Code: git `{manifest.code.git_sha or 'n/a'}`, code fingerprint `{manifest.code.code_fingerprint}`",
        (
            "- Every document carries `provenance` (source URI, record locator, record id, source fingerprint, "
            "transformation history)."
        ),
        f"- Verify or reproduce: `{manifest.reproduce['command']}`",
        "",
        "## Loading",
        "",
        "```python",
        "import datasets",
        'ds = datasets.load_dataset("parquet", data_files={"train": "data/train-*.parquet"})',
        "",
        "import duckdb",
        "duckdb.sql(\"SELECT domain, count(*) FROM 'data/*.parquet' GROUP BY domain\").show()",
        "```",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
